-- Data/CameraPresets.lua
-- Camera preset framework for T.Preview model viewing.
--
-- Two donor sources feed this module, harvested by
-- tools/data-pipeline/sources/camerapresets-importer.py:
--
--   1) HomeBound (db.lua)
--      db.modelPositions is keyed by modelFileID (display ID / file ID)
--      with the schema:
--          [fileID] = {
--              model_x  = number,  -- horizontal model offset
--              model_z  = number,  -- depth/forward model offset
--              camera_y = number,  -- camera vertical offset
--              zoom     = number,  -- camera zoom distance
--          }
--      421 entries. (db.lua holds six other unrelated tables; only
--      modelPositions feeds this one.)
--
--   2) HousingCraftTracker_Data (Data.lua)
--      HousingCraftTrackerData[profession][expansion][itemID]["cam"] with schema:
--          ["cam"] = {
--              zoom     = number,
--              x        = number,
--              y        = number,
--              z        = number?,   -- optional depth offset
--              scale    = number,
--              noRotate = boolean?,  -- disables auto-rotation
--              facing   = number?,   -- locked facing angle (radians)
--          }
--      305 entries keyed by itemID. Keyed by item only: framing does not
--      depend on which profession tab reached the model.
--
-- Public API:
--   T.CameraPresets:GetByItemID(itemID) -> { zoom, x, y, scale, noRotate, facing }
--   T.CameraPresets:GetByFileID(fileID) -> { zoom, x, y, scale }
--
-- Both tables are filled by Data/CameraPresetData.lua, generated by
-- tools/data-pipeline/sources/camerapresets-importer.py and loaded immediately
-- after this file. This file owns the schema and the lookup API; the generated
-- file only supplies rows, so the two can be regenerated independently.
-- Lookups still return nil for anything the donors never covered.

local T = FabledUI_UIToolkit
T = T or {}
_G.FabledUI_UIToolkit = T

T.CameraPresets = T.CameraPresets or {}
local CameraPresets = T.CameraPresets

---------------------------------------------------------------------
-- Preset tables (populated by offline harvest pipeline)
---------------------------------------------------------------------

-- Exposed on CameraPresets (rather than kept as file-locals) so the generated
-- Data/CameraPresetData.lua can fill them without this file being rewritten.
-- Keyed by modelFileID. Schema: { model_x, model_z, camera_y, zoom }
--
-- These are HomeBound's numbers and they are CAMERA-relative. HomeBound applies
-- them as (main.lua:929-931):
--     model:MakeCurrentCameraCustom()
--     model:SetPosition(model_x, 0, model_z)
--     model:SetCameraPosition(0, 0, camera_y)
--     model:SetCameraDistance(zoom)
CameraPresets.FileIDPresets = CameraPresets.FileIDPresets or {}

-- Keyed by itemID. Schema: { zoom, x, y, scale, noRotate?, facing?, z? }
--
-- WARNING: these are HousingCraftTracker's numbers and its `zoom` is NOT a
-- camera distance. HCT feeds it straight into SetPosition as the depth
-- argument (HousingCraftTracker.lua:271-275):
--     model:SetPosition(zoom, x, y)   -- zoom is arg1: depth
--     model:SetPitch(z)               -- the `z` field is pitch, not position
--     model:SetScale(scale)
--     model:SetFacing(facing)
-- Roughly a third of the harvested rows carry a negative `zoom`, which is
-- meaningless as a camera distance and would throw or clamp. The two donors
-- share a field name and nothing else; do not merge them into one shape.
CameraPresets.ItemIDPresets = CameraPresets.ItemIDPresets or {}

local FILE_ID_PRESETS = CameraPresets.FileIDPresets
local ITEM_ID_PRESETS = CameraPresets.ItemIDPresets

---------------------------------------------------------------------
-- Public API
---------------------------------------------------------------------

--- Look up a model-framing preset by item ID (HousingCraftTracker donor).
--- Field names describe what each number DOES, not what the donor called it:
--- HCT's `zoom` is a SetPosition depth argument and its `z` is a pitch.
---@param itemID number? nil is accepted and returns nil
---@return table|nil preset { depth, x, y, pitch, scale, noRotate, facing }
function CameraPresets:GetByItemID(itemID)
    if type(itemID) ~= "number" then
        return nil
    end
    local entry = ITEM_ID_PRESETS[itemID]
    if not entry then
        return nil
    end
    return {
        depth    = entry.zoom,   -- SetPosition arg1. NOT a camera distance.
        x        = entry.x,      -- SetPosition arg2
        y        = entry.y,      -- SetPosition arg3
        pitch    = entry.z,      -- SetPitch
        scale    = entry.scale,  -- SetScale
        noRotate = entry.noRotate,
        facing   = entry.facing,
    }
end

--- Look up a camera preset by display/file ID (HomeBound donor).
--- These ARE camera numbers: `zoom` is a real SetCameraDistance value.
---@param fileID number? nil is accepted and returns nil
---@return table|nil preset { zoom, modelX, modelZ, cameraY }
function CameraPresets:GetByFileID(fileID)
    if type(fileID) ~= "number" then
        return nil
    end
    local entry = FILE_ID_PRESETS[fileID]
    if not entry then
        return nil
    end
    return {
        zoom    = entry.zoom,      -- SetCameraDistance
        modelX  = entry.model_x,   -- SetPosition arg1
        modelZ  = entry.model_z,   -- SetPosition arg3
        cameraY = entry.camera_y,  -- SetCameraPosition arg3
    }
end

---------------------------------------------------------------------
-- Application
---------------------------------------------------------------------

--- Frame a model using whichever donor preset covers it.
---
--- This exists so no caller has to know which donor a preset came from. The
--- two schemas are not interchangeable -- HCT's `zoom` is a position depth and
--- HomeBound's is a camera distance -- so a caller that fetched a preset and
--- applied it "generically" would push a third of the item-ID rows to negative
--- camera distances. Each branch below replays its own donor's call sequence.
---
--- itemID is tried first: HCT's rows are hand-tuned per craftable decor, while
--- HomeBound's are keyed by the shared model file and are therefore coarser.
---
---@param model table PlayerModel/Model frame (already loaded)
---@param itemID number? item ID to look up in the HCT table
---@param fileID number? model file ID to look up in the HomeBound table
---@return boolean applied
---@return string|nil source "item" or "file" when applied
function CameraPresets:Apply(model, itemID, fileID)
    if type(model) ~= "table" and type(model) ~= "userdata" then
        return false, nil
    end

    local item = self:GetByItemID(itemID)
    if item then
        -- HCT positions the MODEL and leaves the camera alone.
        if model.SetPosition then
            pcall(model.SetPosition, model, item.depth or 0, item.x or 0, item.y or 0)
        end
        if item.pitch and model.SetPitch then
            pcall(model.SetPitch, model, item.pitch)
        end
        if item.scale and model.SetScale then
            pcall(model.SetScale, model, item.scale)
        end
        if item.facing and model.SetFacing then
            pcall(model.SetFacing, model, item.facing)
        end
        return true, "item"
    end

    local file = self:GetByFileID(fileID)
    if file then
        -- HomeBound moves the CAMERA, and SetCameraPosition/SetCameraDistance
        -- only take effect on a custom camera -- without this the calls are
        -- silently ignored and every model keeps the default framing.
        if model.MakeCurrentCameraCustom then
            pcall(model.MakeCurrentCameraCustom, model)
        end
        if model.SetPosition then
            pcall(model.SetPosition, model, file.modelX or 0, 0, file.modelZ or 0)
        end
        if file.cameraY and model.SetCameraPosition then
            pcall(model.SetCameraPosition, model, 0, 0, file.cameraY)
        end
        if file.zoom and model.SetCameraDistance then
            pcall(model.SetCameraDistance, model, file.zoom)
        end
        return true, "file"
    end

    return false, nil
end

--- Returns true if a preset exists for the given item ID.
---@param itemID number? nil is accepted and returns nil
---@return boolean
function CameraPresets:HasItemID(itemID)
    return type(itemID) == "number" and ITEM_ID_PRESETS[itemID] ~= nil
end

--- Returns true if a preset exists for the given file ID.
---@param fileID number? nil is accepted and returns nil
---@return boolean
function CameraPresets:HasFileID(fileID)
    return type(fileID) == "number" and FILE_ID_PRESETS[fileID] ~= nil
end
