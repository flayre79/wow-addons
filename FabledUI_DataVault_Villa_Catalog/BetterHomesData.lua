function BetterHomesData:GetProfessionEntries()
    local entries = {}
    for _, item in ipairs(self.ProfessionData or {}) do
        entries[#entries + 1] = {
            key = (item.profession or "Unknown") .. ":" .. tostring(item.itemID or 0),
            title = item.name or "Unknown Decor",
            subtitle = (item.profession or "Unknown") .. " • " .. (item.expansion or "Unknown"),
            detail = "BetterHomes profession donor entry.",
            profession = item.profession,
            expansion = item.expansion,
            itemID = item.itemID,
            total = 1,
            owned = 0,
            entryType = "profession",
            decorIds = { item.itemID or 0 },
        }
    end
    return entries
end

function BetterHomesData:GetTreasureEntries()
    local entries = {}
    for _, item in ipairs(self.TreasureData or {}) do
        local mapName = (C_Map and C_Map.GetMapInfo and item.mapID and C_Map.GetMapInfo(item.mapID) and C_Map.GetMapInfo(item.mapID).name) or ("Map " .. tostring(item.mapID or 0))
        entries[#entries + 1] = {
            key = tostring(item.questID or 0),
            title = item.name or ("Treasure " .. tostring(item.questID or 0)),
            subtitle = mapName,
            detail = string.format("BetterHomes treasure route donor. Quest %s at %.1f, %.1f.", tostring(item.questID or 0), tonumber(item.x or 0), tonumber(item.y or 0)),
            mapID = item.mapID, x = item.x, y = item.y, questID = item.questID, total = 1, owned = 0, entryType = "treasure", decorIds = { item.questID or 0 },
        }
    end
    return entries
end

function BetterHomesData:GetVendorsForMap(mapID, includeParents)
    local out = {}
    if not mapID then return out end
    local mapSet = { [mapID] = true }
    if includeParents and C_Map and C_Map.GetMapInfo then
        local seen = {}
        local cursor = mapID
        while cursor and not seen[cursor] do
            seen[cursor] = true
            local info = C_Map.GetMapInfo(cursor)
            cursor = info and info.parentMapID
            if cursor and cursor > 0 then mapSet[cursor] = true end
        end
    end
    for _, vendor in ipairs(self.VendorData or {}) do
        if vendor.mapID and mapSet[vendor.mapID] then out[#out + 1] = vendor end
    end
    return out
end